"""Завдання №186: політика sandbox для агента.

Агент (LLM) просить виконати дію: прочитати/записати файл, піти в мережу, запустити процес.
Модель не межа безпеки: рішення `allow` / `ask` / `deny` приймає код ДО виконання дії, за
правилами та ліміти рахує теж код. Тут пишеться рушій політики; сама дія НЕ виконується.

    policy = {
        "workspace": "/abs/path/to/ws",          # абсолютний шлях робочої теки агента
        "rules": [                                # список правил
            {"effect": "allow" | "ask" | "deny",
             "kind": "file_read" | "file_write" | "net" | "exec",
             "pattern": "<glob>"},
        ],
        "limits": {"max_actions": 50, "max_write_bytes": 1_000_000},   # необовʼязково
    }
    sandbox = Sandbox(policy)
    sandbox.decide({"kind": "file_read", "path": "docs/a.md"})
    # -> {"decision": "allow", "reason": "allow-rule", "rule": 0}

`Sandbox(policy)`
    Перевіряє політику й піднімає `ValueError`, якщо: `workspace` не абсолютний шлях; `rules`
    не список; правило не dict або з невідомими `effect`/`kind` чи `pattern` не непорожній
    рядок; `limits` містить невідомий ключ або значення не `int` >= 0 (`bool` не підходить).
    Політику треба скопіювати: зміна вихідного словника після створення не діє.

`Sandbox.decide(action) -> dict`
    Повертає `{"decision": "allow"|"ask"|"deny", "reason": <код>, "rule": <індекс правила
    або None>}`. Ніколи не піднімає винятків: будь-що некоректне це `deny`.

    Дії (інші ключі ігноруються):
      * `{"kind": "file_read", "path": str}`
      * `{"kind": "file_write", "path": str, "size": int}`   (`size` >= 0, не `bool`)
      * `{"kind": "net", "host": str, "port": int}`          (порт 1..65535, не `bool`)
      * `{"kind": "exec", "argv": [str, ...]}`               (непорожній список)
    Не dict, невідомий `kind` чи відсутні/некоректні поля це `deny` з причиною
    `invalid-action`.

    Порядок рішення:
      1. Некоректна дія, шлях чи хост: `deny` (`invalid-action`, `invalid-path`, `invalid-host`).
      2. Файли поза `workspace` після канонізації: `deny` з причиною `outside-workspace`
         (правила для файлів діють лише всередині `workspace`).
      3. Правила дивляться тільки на ті, у яких `kind` збігається з дією. Пріоритет НЕ залежить
         від порядку правил: будь-яке збіглося `deny` перемагає, інакше будь-яке `ask`, інакше
         `allow`. Причини: `deny-rule`, `ask-rule`, `allow-rule`; `rule` це індекс (перший за
         порядком серед збіглих правил переможного ефекту). Нічого не збіглося: `deny` з
         причиною `default-deny`, `rule` це `None`.
      4. Ліміти (лише якщо рішення було б `allow`): див. нижче. Перевищення: `deny` з
         причиною `limit-exceeded`.

    Файлові шляхи:
      * відносний шлях рахується від `workspace`;
      * `path` має бути непорожнім рядком без символу NUL, інакше `invalid-path`;
      * КАНОНІЧНИЙ шлях це `os.path.realpath(...)`: прибирає `.`/`..` і розкриває symlink
        (навіть коли файлу не існує);
      * ЛЕКСИЧНИЙ шлях це `os.path.normpath(...)` без розкриття symlink;
      * шлях для правил це відносний до канонічного `workspace` шлях з роздільником `/`;
      * `deny` і `ask` перевіряються і для канонічного, і для лексичного шляху (збіг будь-якого
        достатній), `allow` лише для канонічного: symlink не може вивести з-під `deny`, а
        символічне посилання всередині дозволеної теки на заборонене місце не дає доступу;
      * шлях, що виходить за `workspace` (канонічний), це `outside-workspace`.

    Glob-шаблони для файлів (відносно `workspace`): `*` будь-які символи крім `/`, `?` один
    символ крім `/`, `**/` нуль або більше тек, `**` будь-що разом із `/`; інші символи
    буквальні. `deny` та `ask` порівнюються БЕЗ урахування регістру (на ФС без чутливості до
    регістру `SECRETS/` це та сама тека), `allow` З урахуванням регістру.

    Мережа: хост нормалізується (нижній регістр, без кінцевої крапки). Дозволені лише символи
    `a-z 0-9 . -`, інакше `invalid-host`. Хост, що складається тільки з цифр і крапок або
    починається з `0x`, має бути канонічною IPv4 `a.b.c.d` (кожне 0..255, без ведучих нулів),
    інакше `invalid-host` (так відсікаються `2852039166`, `0xa9fea9fe`, `0251.0376.0251.0376`).
    Рядок для правил: `"<host>:<port>"`; шаблон: `*` будь-які символи, `?` один символ,
    без урахування регістру.

    Процеси: рядок для правил це імʼя виконуваного файла (останній компонент `argv[0]` за `/`
    чи `\\`, без суфікса `.exe` будь-якого регістру), далі через пробіл решта `argv`, зʼєднана
    пробілом (`["/usr/bin/git", "status", "-s"]` це `"git status -s"`). Шаблон: `*` будь-які
    символи, `?` один символ; `deny`/`ask` без урахування регістру, `allow` з урахуванням.
    `argv` має бути списком непорожніх рядків без NUL (перший елемент непорожній), інакше
    `invalid-action`.

    Ліміти (необовʼязкові ключі `limits`):
      * `max_actions`: скільки дій може отримати `allow` за життя `Sandbox`; дія, що
        перевищила б ліміт, отримує `deny` (`limit-exceeded`) і не враховується;
      * `max_write_bytes`: сума `size` усіх дозволених `file_write`; запис, що виходить за
        залишок, отримує `deny` (`limit-exceeded`) і не враховується (рівно до межі дозволено).
    `ask` та `deny` лічильники не збільшують.
"""


