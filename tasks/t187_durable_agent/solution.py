"""Завдання №187: durable execution агента.

Агент виконує кілька кроків: викликає інструменти (зняти гроші, надіслати лист, створити
тікет). Процес може впасти будь-коли: між кроками, посередині кроку, у момент запису в журнал.
Після рестарту агент має ДОГРАТИСЬ до кінця так, щоб жодна побічна дія не виконалась двічі
(Temporal, LangGraph checkpointer, Inngest працюють за тим самим принципом: журнал подій і replay).

Агент це звичайна функція від контексту: `agent(run)`. Її код детермінований: вона просто
викликає `run.call(...)` та `run.once(...)` у тому самому порядку. Після падіння функцію
запускають ЗНОВУ З ПОЧАТКУ, а контекст «програє» (replay) уже записані кроки з журналу,
не виконуючи їх повторно.

Що надає тест (ти пишеш лише `DurableRun`):
  * `journal`: об'єкт із двома методами. `journal.append(event: dict) -> None` дописує
    подію в кінець (у тесті під час падіння може підняти `Crash` ДО запису або ПІСЛЯ запису).
    `journal.read() -> list[dict]` повертає усі події всіх запусків у порядку запису (копії).
    Події мають бути JSON-подібними (dict, list, str, int, float, bool, None).
  * `tools`: `dict[str, callable]`. Інструмент викликається як
    `tools[name](**args, idempotency_key=key)` і повертає JSON-подібний результат. Зовнішня
    система дедуплікує за `idempotency_key`: повторний виклик з тим самим ключем не повторює
    побічний ефект, а повертає збережений результат.
  * `Crash`: виняток-імітація падіння процесу (успадковується від `BaseException`). Ти його
    НЕ ловиш і не ковтаєш: він має пройти нагору з `call`/`once`/`run` як є.

`class NonDeterminismError(RuntimeError)`: уже оголошений нижче; піднімай його, коли код
агента під час replay веде себе інакше, ніж у журналі.

`DurableRun(run_id: str, journal, tools: dict)`
    Один логічний запуск агента. Порожній чи не-рядок `run_id` це `ValueError`. Кроки нумеруються з 0 у порядку викликів `call`/`once`.

`DurableRun.run(agent) -> Any`
    1. Читає журнал; якщо для цього `run_id` уже є подія `run_completed`, повертає
       записаний результат, НЕ викликаючи `agent` і жодного інструмента.
    2. Інакше викликає `agent(self)`, а після успішного завершення дописує
       `run_completed` з результатом і повертає цей результат.
    3. Звичайний виняток із `agent` (не `Crash`) летить нагору без запису `run_completed`
       (запуск можна повторити, і він продовжиться з журналу).
    Метод можна викликати на новому `DurableRun` з тим самим `run_id` і тим самим `journal`
    (це і є «рестарт процесу»). Події інших `run_id` в журналі ігноруються.

`DurableRun.call(tool: str, args: dict) -> Any`
    Крок-виклик інструмента з номером `seq`.
      * Невідомий `tool`: `KeyError`, у журнал НІЧОГО не пишеться.
      * Якщо в журналі вже є завершений крок `seq`: перевір, що інструмент і `args` збігаються
        з записаними, інакше `NonDeterminismError`; поверни записаний результат, НЕ викликаючи
        інструмент.
      * Якщо є лише початок кроку (`step_started` без завершення, тобто падіння сталося
        посередині): виклич інструмент ще раз з ТИМ САМИМ `idempotency_key`, запиши завершення.
      * Інакше: спершу допиши `step_started` (WAL: намір записано ДО дії), потім виклич
        інструмент, потім допиши `step_completed` з результатом.
      * `idempotency_key` рівно `f"{run_id}:{seq}"` (стабільний між рестартами; два однакові
        виклики поспіль це два різні кроки з різними ключами).
      * Результат, який повертається агенту, це КОПІЯ: якщо агент змінить його, журнал та
        наступний replay не повинні змінитись. Те саме для `args`, що записуються.
      * Якщо інструмент піднімає звичайний `Exception`, він летить нагору, крок лишається
        незавершеним (наступний запуск повторить його з тим самим ключем).

`DurableRun.once(name: str, fn: callable) -> Any`
    Крок-чекпоінт: недетерміноване обчислення без зовнішнього ефекту (відповідь моделі, час,
    випадкове число), результат якого треба зафіксувати. Теж займає номер кроку `seq`.
      * Якщо в журналі є завершений крок `seq` з тим самим `name`: поверни записане значення,
        НЕ викликаючи `fn`. Інший `name` або тип кроку це `NonDeterminismError`.
      * Інакше виклич `fn()`, допиши подію `step_completed` з результатом (копія!) і поверни
        його. `fn` викликається щонайбільше раз на кожне записане завершення (якщо падіння
        сталося після `fn`, але до запису, `fn` виконається ще раз: це нормально).

Формат подій (поля, які читає тест, окрім назв нижче додавати можна що завгодно): кожна
подія це dict з `"run_id"` і `"type"` (`step_started`, `step_completed`, `run_completed`),
кроки мають `"seq"`.
"""


class Crash(BaseException):
    """Імітація падіння процесу (у реальному житті: kill -9, OOM, відключення живлення)."""


class NonDeterminismError(RuntimeError):
    """Код агента під час replay не збігається з журналом."""


class DurableRun:
    def __init__(self, run_id: str, journal, tools: dict):
        raise NotImplementedError

    def run(self, agent):
        raise NotImplementedError

    def call(self, tool: str, args: dict):
        raise NotImplementedError

    def once(self, name: str, fn):
        raise NotImplementedError
