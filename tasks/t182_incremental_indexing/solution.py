"""Завдання №182: інкрементальна індексація з правами доступу.

Корпоративний RAG-індекс щодня оновлюється. Перебудова всього корпусу коштує грошей (embeddings) і часу,
а помилки в індексі це інциденти безпеки: видалений документ усе ще «відповідає», відкликаний доступ
працює до наступної перебудови, а фільтр прав застосовується ПІСЛЯ пошуку й повертає менше результатів
(або взагалі їх ловить на боці клієнта) (CWE-863, ~CWE-639). Реалізуй індекс у памʼяті.

`split_chunks(text) -> list[str]`
    Чанки це абзаци: текст ділиться за порожніми рядками (`re.split(r"\\n\\s*\\n", text)`), кожен чанк обрізається
    по краях (`strip()`), порожні відкидаються. Порядок і дублікати зберігаються.
`content_hash(chunk) -> str`
    `hashlib.sha256(chunk.encode("utf-8")).hexdigest()`.

`IncrementalIndex(embed, model="v1")`
    `embed(text) -> list[float]` перетворює текст на вектор; `model` це ідентифікатор моделі embeddings.

    `.upsert(doc_id, text, acl) -> dict`
        Додає чи оновлює документ. `doc_id`: непорожній `str`; `text`: `str`; `acl`: множина, список чи
        кортеж непорожніх рядків-субʼєктів (користувачі й групи), які ЗАРАЗ мають право читати документ
        (порожній acl: не читає ніхто). `None`, рядок замість колекції чи нерядковий елемент це
        `ValueError` (fail closed: «без acl» не означає «публічний»).
        Чанки документа ідентифікуються ХЕШЕМ ВМІСТУ, а не позицією: перестановка абзаців чи вставка
        абзацу на початок не змінює решти чанків. Однакові абзаци всередині одного документа це один
        чанк. Порівнюються набори хешів нового й старого тексту:
          * нові хеші: `embed` викликається ОДИН раз на кожен новий чанк (у порядку появи в тексті);
          * хеші, яких більше немає в тексті: чанк видаляється з індексу (застарілі чанки не лишаються);
          * решта: не перераховується (`embed` не викликається).
        `acl` застосовується завжди, навіть коли текст не змінився (це змінює права без `embed`).
        Однакові абзаци в РІЗНИХ документах це різні чанки (кожен документ має свої).
        Операція атомарна: якщо `embed` кинув виняток, виняток іде нагору, а індекс, включно з `acl`
        документа, лишається таким, яким був.
        Повертає `{"added": n, "removed": n, "unchanged": n}`: кількості унікальних чанків документа.
        Порожній текст (чи лише порожні рядки) це документ без чанків (старі чанки видаляються).
    `.delete(doc_id) -> int`
        Видаляє документ і всі його чанки, повертає кількість видалених чанків (невідомий: 0).
    `.search(query, principals, k=3) -> list[dict]`
        `principals`: колекція рядків (субʼєкт плюс його групи), `None` чи не колекція це `ValueError`.
        Фільтр прав діє ДО відбору top-k: розглядаються лише чанки документів, у `acl` яких є хоч один
        зі `principals`. Тож якщо найсхожіші чанки заборонені, повертаються k найсхожіших ДОЗВОЛЕНИХ, а не
        менше. Порожні `principals`: `[]`. `k < 1`: `ValueError`.
        Запит вбудовується поточною `embed` рівно один раз. Score це скалярний добуток векторів
        (без округлення), повертаються лише score > 0, за спаданням score, при рівності за
        `(doc_id, позиція чанка в документі)`. Елемент: `{"doc_id", "chunk", "score"}`. Права читаються з
        ПОТОЧНОГО `acl` документа: відкликання діє одразу.
    `.reindex(embed, model) -> int`
        Перехід на нову модель embeddings. Якщо `model` збігається з поточною: нічого не робить, `0`
        (нова `embed` не викликається). Інакше нова `embed` викликається один раз для КОЖНОГО збереженого
        чанка, після чого індекс перемикається на `(embed, model)` цілком; повертає кількість
        перерахованих чанків. Якщо `embed` кинула виняток, індекс лишається на старій моделі.
        Після `reindex` нові чанки (`upsert`) і запити використовують нову `embed`.
    `.stats() -> dict`
        `{"docs": кількість документів, "chunks": кількість чанків, "model": поточна модель}`.
"""
