"""Завдання №175: менеджер контекстного вікна.

Контекст запиту до моделі складається із секцій: інструкції, памʼять, документи (RAG) та
історія діалогу. Токенів завжди бракує: довга історія витісняє документи, а модель гірше
користується тим, що лежить посередині (lost in the middle). Потрібна функція, що збирає
контекст у бюджет токенів за чіткими пріоритетами. Токени рахує функція `count_tokens(text)`,
яку передають параметром (у тестах це кількість слів); модель підроблена функцією `summarize`.

`assemble(instructions, memory, documents, history, budget, count_tokens, summarize=None,
          compact_at=0.8, keep_recent=2) -> dict`

Вхід:
    instructions   str. Закріплені інструкції: НІКОЛИ не обрізаються й не відкидаються.
    memory         list[str] у порядку важливості (найважливіше перше).
    documents      list[{"text": str, "score": float}], score більший означає релевантніший.
    history        list[{"role": str, "content": str}] від найстарішого до найновішого.
    budget         int >= 1, максимум токенів у ПІДСУМКУ.
    keep_recent    int >= 1: стільки останніх ходів історії не стискають.
    compact_at     0 < compact_at <= 1: частка бюджету, понад яку вмикають компактизацію.
    Неправильні budget (не int, bool, < 1), keep_recent, compact_at це `ValueError`.

Токени підсумку = сума `count_tokens(текст)` по всіх включених текстах (для ходів історії
рахується `content`, без ролі). Підсумок не має перевищувати `budget` (рівно `budget` можна).

Кроки:
1. Якщо `count_tokens(instructions) > budget`: `ValueError`.
2. Компактизація. Якщо `summarize` задано, ПОВНИЙ вхід (усе, що прийшло, без обрізання) має
   СУВОРО більше за `compact_at * budget` токенів і ходів історії більше за `keep_recent`:
   старі ходи (усі, крім останніх `keep_recent`) віддаються в `summarize(turns)` рівно ОДИН
   раз, де `turns` це список рядків `"<role>: <content>"` у хронологічному порядку; результат
   це один рядок-підсумок. Якщо підсумок НЕ коротший за сумарні токени цих старих ходів,
   його відкидають, а історія лишається як була. Інакше старі ходи замінює підсумок.
   Нижче порога чи без `summarize` функція не викликається.
3. Обрізання, поки підсумок > budget, строго в такому порядку:
   a) документи: спершу з найменшим `score` (при рівності відкидається той, що пізніший у вході);
   b) памʼять: з кінця списку;
   c) історія: спершу підсумок (якщо він є), потім ходи від найстарішого. Останній хід
      історії не відкидається ніколи.
   Якщо навіть інструкції + останній хід > budget: `ValueError`.
4. Порядок секцій у виході: інструкції, памʼять (як у вході), документи, підсумок, історія.
   Документи розташовують «краї важливіші за середину»: найкращий за score ПЕРШИЙ, другий
   найкращий ОСТАННІЙ, третій другий з початку, четвертий другий з кінця і так далі
   (5 документів за спаданням score 1..5 дають порядок 1, 3, 5, 4, 2). Рівні score: за
   порядком у вході.

Повертає:
    {"messages": [{"section": "instructions"|"memory"|"documents"|"summary"|"history",
                   "role": str, "text": str}, ...],
     "tokens": int,
     "dropped": {"documents": n, "memory": n, "history": n},
     "compacted": bool,          # підсумок потрапив у результат
     "compacted_turns": int}     # скільки ходів він замінив (0, якщо compacted=False)
    role: "system" для інструкцій, памʼяті, документів і підсумку; для історії роль ходу.
    Якщо підсумок відкинуто на кроці 3c, його ходи рахуються в `dropped["history"]`,
    `compacted` це False, `compacted_turns` це 0.
Вхідні списки й словники змінювати не можна.
"""


